// 메이저 아르카나 22장의 해석 데이터 (정방향 / 역방향)
//
// 카드 한 장 = 방향마다 세 가지:
//   keywords: 핵심 단어 2~3개 (결과 화면의 태그 + 종합 한 줄에 사용)
//   meaning : 의미 구절. "~는"으로 끝나서 문장 틀 "{meaning} 흐름" 처럼 뒤에 이어 붙일 수 있음
//   action  : 사용자가 실제로 해 볼 수 있는 행동 제안 (완성된 문장, 미래 자리 아래 "이렇게 해 보세요"에 사용)
// 주제(연애·금전·진로)와 자리(과거·현재·미래)에 맞는 문장 틀은 interpret.ts에 있습니다.
//
// [AI 사용 표시] 해석 문장은 일반적인 타로 카드 의미를 바탕으로 Claude(AI)가 작성했습니다. (AI 사용 비율: 약 100%)

/** 한 방향(정 또는 역)의 해석 */
export type MeaningSide = {
  keywords: string[];
  meaning: string;
  action: string;
};

/** 카드 한 장의 해석 (정방향 up / 역방향 rev) */
export type CardMeaning = { up: MeaningSide; rev: MeaningSide };

/**
 * 데이터를 짧게 쓰기 위한 도우미: card([정 키워드], 정 의미, 정 행동, [역 키워드], 역 의미, 역 행동)
 * [AI 도움: Claude]
 */
export function card(
  upKeywords: string[],
  upMeaning: string,
  upAction: string,
  revKeywords: string[],
  revMeaning: string,
  revAction: string,
): CardMeaning {
  return {
    up: { keywords: upKeywords, meaning: upMeaning, action: upAction },
    rev: { keywords: revKeywords, meaning: revMeaning, action: revAction },
  };
}

