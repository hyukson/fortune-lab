/** 순위 → 구간 (1위 / 2~4위 / 5~8위 / 9~11위 / 12위) */
export function getTier(rank: number): Tier {
  if (rank === 1) return 'best';
  if (rank <= 4) return 'good';
  if (rank <= 8) return 'normal';
  if (rank <= 11) return 'low';
  return 'worst';
}

