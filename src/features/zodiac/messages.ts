/** 받침 여부에 따라 을/를, 이/가, 은/는, 으로/로 고르기 */
export function josa(word: string, pair: '을/를' | '이/가' | '은/는' | '으로/로'): string {
  const code = word.charCodeAt(word.length - 1) - 0xac00;
  const isHangul = code >= 0 && code <= 11171;
  const finalConsonant = isHangul ? code % 28 : 0;
  const [withBatchim, withoutBatchim] = pair.split('/');
  if (pair === '으로/로') {
    // 받침이 없거나 'ㄹ' 받침이면 '로'
    return word + (finalConsonant === 0 || finalConsonant === 8 ? withoutBatchim : withBatchim);
  }
  return word + (finalConsonant !== 0 ? withBatchim : withoutBatchim);
}

